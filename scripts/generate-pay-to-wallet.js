// generate-pay-to-wallet.js — create a fresh EOA wallet for x402 revenue collection.
// Saves to config/keys/pay-to-new.json (gitignored). Prints address only; never prints key.
const { ethers } = require('ethers');
const fs = require('fs');
const path = require('path');

const KEY_FILE = path.join(__dirname, '..', 'config', 'keys', 'pay-to-new.json');

if (fs.existsSync(KEY_FILE)) {
  const existing = JSON.parse(fs.readFileSync(KEY_FILE, 'utf8'));
  console.log(`Wallet already exists at ${KEY_FILE}:`);
  console.log(`  Address: ${existing.address}`);
  console.log(`  Created: ${existing.createdAt}`);
  process.exit(0);
}

const wallet = ethers.Wallet.createRandom();
const record = {
  address: wallet.address,
  createdAt: new Date().toISOString(),
  purpose: 'Dedicated x402 revenue collector (replace 0x367F...1a03)',
  note: `Generated by generate-pay-to-wallet.js on ${new Date().toISOString()}. Transfer remaining USDC+ETH from treasury 0x367F1b3D8Ca90D1e087481a9A40d585Bf3451a03 via MetaMask, then update Vercel PAY_TO env var.`,
  privateKey: wallet.privateKey,
};

fs.mkdirSync(path.dirname(KEY_FILE), { recursive: true });
fs.writeFileSync(KEY_FILE, JSON.stringify(record, null, 2), 'utf8');
console.log(`New wallet generated -> ${KEY_FILE}`);
console.log(`Address: ${wallet.address}`);
console.log(`Private key stored locally only (gitignored).`);
console.log(`Next: vercel env add --scope solmount --project autotasker-hub PAY_TO ${wallet.address} --type secret`);
